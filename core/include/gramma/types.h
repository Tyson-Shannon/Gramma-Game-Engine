#ifndef GRAMMA_TYPES_H
#define GRAMMA_TYPES_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <gramma/target.h>

/* Portable result codes. Positive values keep enum conversions safe on 8-bit. */
typedef enum {
    GR_OK = 0,
    GR_ERR_INVALID_ARG = 1,
    GR_ERR_NO_MEMORY = 2,
    GR_ERR_UNSUPPORTED = 3,
    GR_ERR_BACKEND = 4,
    GR_ERR_NOT_FOUND = 5
} gr_result;

typedef enum {
    GR_PLAYER_1 = 0,
    GR_PLAYER_2 = 1,
    GR_PLAYER_COUNT = 2
} gr_player;

/* Canonical pad. Games declare which buttons they need at build time. */
typedef enum {
    GR_BTN_UP = 0,
    GR_BTN_DOWN,
    GR_BTN_LEFT,
    GR_BTN_RIGHT,
    GR_BTN_A,
    GR_BTN_B,
    GR_BTN_X,
    GR_BTN_Y,
    GR_BTN_L,
    GR_BTN_R,
    GR_BTN_START,
    GR_BTN_SELECT,
    GR_BTN_COUNT
} gr_button;

/* 15-bit RGB, the common visual language of retro hardware. */
typedef uint16_t gr_color;
#define GR_RGB(r, g, b) ((gr_color)((uint16_t)(((uint16_t)(r) & 0x1f) << 10) | \
                                    ((uint16_t)(g) & 0x1f) << 5 |             \
                                    ((uint16_t)(b) & 0x1f)))

typedef struct gr_sfx_def gr_sfx_def;

/*
 * A tileset is packed 8x8 tiles in row-major order, MSB-first within a byte.
 * Index 0 is transparent. Generated by the asset pipeline from a PNG.
 */
typedef struct {
    uint16_t       tile_count;
    uint8_t        bpp;
    const uint8_t *tiles;
    const gr_color *palette;
    uint8_t        palette_size;
} gr_tileset;

/* Row-major 8x8 tile indices, generated from a PNG background or Tiled map. */
typedef struct {
    uint16_t        width;  /* in tiles */
    uint16_t        height; /* in tiles */
    const uint16_t *tiles;
} gr_map;

typedef struct {
    const gr_tileset *tileset;
    const gr_map     *map;
    uint8_t          pal_slot;
    int16_t          scroll_x;
    int16_t          scroll_y;
    bool             visible;
} gr_bg;

typedef struct {
    const gr_tileset *tileset;
    uint8_t          pal_slot;
    uint8_t          frame;
    uint8_t          frame_w; /* frame size in tiles */
    uint8_t          frame_h;
    uint8_t          flip;    /* GR_FLIP_X | GR_FLIP_Y */
    bool             visible;
    int16_t          x;
    int16_t          y;
} gr_sprite;

#define GR_FLIP_X 0x01u
#define GR_FLIP_Y 0x02u

typedef struct gr_actor gr_actor;
typedef void (*gr_actor_update_fn)(gr_actor *actor, gr_fixed dt);

typedef struct {
    const char           *name;
    const gr_tileset     *tileset;
    gr_fixed              x;
    gr_fixed              y;
    gr_fixed              vx;
    gr_fixed              vy;
    uint8_t               pal_slot;
    uint8_t               frame_w;
    uint8_t               frame_h;
    uint8_t               frame;
    gr_actor_update_fn    update;
    void                 *userdata;
} gr_actor_def;

struct gr_actor {
    gr_sprite           sprite;
    gr_fixed            x;
    gr_fixed            y;
    gr_fixed            vx;
    gr_fixed            vy;
    uint8_t             id;
    bool                alive;
    gr_actor_update_fn  update;
    void               *userdata;
};

typedef struct {
    const char *name;
    gr_bg      *bg;
    void       (*load)(void);
    void       (*unload)(void);
    void       (*update)(gr_fixed dt);
    void       (*draw)(void);
} gr_scene;

typedef enum {
    GR_WAVE_SQUARE = 0,
    GR_WAVE_TRIANGLE,
    GR_WAVE_SAW,
    GR_WAVE_NOISE,
    GR_WAVE_PCM
} gr_wave;

/* Small PCM blob, emitted by the pipeline from a WAV file. */
typedef struct {
    uint16_t     sample_rate;
    uint16_t     length;
    const int8_t *data;
} gr_pcm;

struct gr_sfx_def {
    gr_wave      wave;
    uint16_t     freq_hz;
    int16_t      freq_slope_hz; /* Hz per second, for sweeps */
    uint16_t     duration_ms;
    uint8_t      volume;        /* 0..15 */
    const gr_pcm *pcm;
};

/* One 16th-note. freq_hz == 0 is a rest. channel selects a mixer channel. */
typedef struct {
    uint16_t freq_hz;
    uint16_t ticks;
    uint8_t  volume;
    uint8_t  channel;
    gr_wave  wave;
} gr_note;

typedef struct {
    uint16_t      bpm;
    uint16_t      note_count;
    const gr_note *notes;
    bool          loop;
} gr_song;

typedef struct {
    const char   *title;
    uint16_t      width;
    uint16_t      height;
    uint8_t       max_actors;
    uint8_t       players;
    uint16_t      required_buttons[GR_PLAYER_COUNT];
    void        (*game_init)(void);
    void        (*game_update)(gr_fixed dt);
    void        (*game_draw)(void);
    const gr_sfx_def *const *sfx;
    uint16_t      sfx_count;
} gr_config;

#endif /* GRAMMA_TYPES_H */
