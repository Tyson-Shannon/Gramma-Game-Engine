"""WAV -> int8 PCM + DMC samples, emitted as C and ca65 assembly.

The normal ``gr_pcm`` blob feeds the PC/GB/SMS backends. The NES APU has a
different, 4-bit delta-modulated channel, so the same source WAV is also
encoded here as a 64-byte-aligned DMC sample. Emission is still entirely
ahead-of-time: consoles only see constant arrays and a ``gr_dmc`` descriptor.
"""

from __future__ import annotations

import re
import struct
import wave
from dataclasses import dataclass

from .project import AudioAsset


MAX_SAMPLES = 16384  # fits in gr_pcm.length (uint16_t), ~0.74s at 22050 Hz
MAX_DMC_BYTES = 16384  # keeps one sample well inside a 16 KB PRG bank
# NTSC APU DMC rate index -> playback frequency. Hardware counts CPU cycles
# per sample: 428, 380, ... 74 at 1.789773 MHz.
DMC_RATES_HZ = (4182, 4710, 5264, 5887, 6629, 7457, 8363, 9419,
                10653, 11932, 13356, 14914, 16885, 19040, 21307, 24186)


@dataclass
class AudioResult:
    name: str
    sample_rate: int
    length: int
    duration_ms: int
    source: str
    rom_bytes: int
    source_text: str
    dmc_rate: int = 15
    dmc_length: int = 0
    dmc_bytes: int = 0
    dmc_asm_text: str = ""


def _decode_wav(path) -> tuple[list[float], int]:
    with wave.open(str(path), "rb") as wav:
        channels = wav.getnchannels()
        width = wav.getsampwidth()
        rate = wav.getframerate()
        frames = wav.readframes(wav.getnframes())

    if width == 1:
        samples = [(byte - 128) / 128.0 for byte in frames]
    elif width == 2:
        count = len(frames) // 2
        samples = [v / 32768.0
                   for v in struct.unpack("<" + "h" * count, frames[:count * 2])]
    else:
        raise ValueError("only 8-bit and 16-bit PCM WAV files are supported")

    if channels > 1:
        samples = [sum(samples[i:i + channels]) / channels
                   for i in range(0, len(samples), channels)]
    return samples, rate


def _resample(samples: list[float], src_rate: int, dst_rate: int,
              limit: int = MAX_SAMPLES) -> list[float]:
    if src_rate == dst_rate or not samples:
        return samples[:limit]
    ratio = src_rate / dst_rate
    out = []
    position = 0.0
    while position < len(samples) and len(out) < limit:
        i = int(position)
        frac = position - i
        a = samples[i]
        b = samples[min(i + 1, len(samples) - 1)]
        out.append(a * (1.0 - frac) + b * frac)
        position += ratio
    return out


def encode_dmc(samples: list[float], src_rate: int, rate_index: int,
               loop: bool = False) -> bytes:
    """Encode floats in [-1, 1] as NES DMC bytes.

    Each byte moves the 7-bit DAC by a signed delta of 1..8; a zero byte holds
    the current level. Large jumps emit several bytes so the result stays close
    to the source waveform without needing a coarser quantization table.
    """
    if not 0 <= rate_index < len(DMC_RATES_HZ):
        raise ValueError(f"DMC rate index must be 0..15, got {rate_index}")
    target_rate = DMC_RATES_HZ[rate_index]
    values = _resample(samples, src_rate, target_rate, MAX_SAMPLES)
    dac = 64
    data = bytearray()
    for value in values:
        target = max(0, min(127, round((value + 1.0) * 63.5)))
        delta = target - dac
        while delta != 0:
            step = max(-8, min(8, delta))
            byte = (0x01 if step > 0 else 0x00) | ((abs(step) - 1) << 1)
            data.append(byte)
            dac += step
            delta -= step
        if len(data) >= MAX_DMC_BYTES:
            break
    if not data:
        return b""
    # The length register counts 16-byte units, so pad with "hold" bytes.
    pad = (-len(data)) % 16
    data.extend(b"\x00" * pad)
    if loop:
        data[0] = 0x00  # avoid a DC step when the player wraps to byte zero
    return bytes(data)


def _dmc_sources(ident: str, data: bytes, rate: int, loop: bool) -> tuple[str, str]:
    rows = []
    for start in range(0, len(data), 16):
        row = ", ".join(f"${value:02X}" for value in data[start:start + 16])
        rows.append(f"        .byte {row}")
    asm = "\n".join([
        "; Generated by the Gramma asset pipeline. DO NOT EDIT.",
        '        .segment "DMC"',
        "        .align 64",
        f"        .export _{ident}_dmc_data",
        f"_{ident}_dmc_data:",
        *rows,
        "",
    ])
    c_text = "\n".join([
        f"extern const uint8_t {ident}_dmc_data[];",
        f"static const gr_dmc {ident}_dmc = {{",
        f"    {rate}, {len(data)}, {ident}_dmc_data, "
        f"{'true' if loop else 'false'}",
        "};",
        "",
    ])
    return c_text, asm


def process_audio(asset: AudioAsset, include_dmc: bool = False) -> AudioResult:
    if not asset.file.is_file():
        raise FileNotFoundError(f"missing audio: {asset.file}")
    samples, source_rate = _decode_wav(asset.file)
    samples = _resample(samples, source_rate, asset.sample_rate)[:MAX_SAMPLES]
    if not samples:
        raise ValueError(f"{asset.name}: empty WAV file")
    pcm = [max(-127, min(127, round(value * 127))) for value in samples]
    duration_ms = len(pcm) * 1000 // asset.sample_rate
    ident = re.sub(r"[^A-Za-z0-9_]", "_", asset.name)
    values = ", ".join(str(v) for v in pcm)

    dmc_def, asm_text, dmc_data = "", "", b""
    # An invalid rate is reported as a structured budget violation before the
    # CLI builds, so generation stays able to emit the portable PCM in that case.
    if include_dmc and 0 <= asset.dmc_rate <= 15:
        dmc_data = encode_dmc(samples, source_rate, asset.dmc_rate,
                              asset.dmc_loop)
        if dmc_data:
            dmc_def, asm_text = _dmc_sources(ident, dmc_data, asset.dmc_rate,
                                             asset.dmc_loop)

    source = "\n".join([
        "/* Generated by the Gramma asset pipeline. DO NOT EDIT. */",
        "#include <gramma/gramma.h>",
        "",
        f"static const int8_t {ident}_pcm_data[{len(pcm)}] = {{ {values} }};",
        "",
        f"static const gr_pcm {ident}_pcm = {{",
        f"    {asset.sample_rate}, {len(pcm)}, {ident}_pcm_data",
        "};",
        "",
        dmc_def,
        f"const gr_sfx_def {ident}_sfx = {{",
        f"    GR_WAVE_PCM, 0, 0, {duration_ms}, 15, &{ident}_pcm, "
        f"{'&' + ident + '_dmc' if dmc_data else 'NULL'}",
        "};",
        "",
    ])
    return AudioResult(
        name=asset.name, sample_rate=asset.sample_rate, length=len(pcm),
        duration_ms=duration_ms, source=asset.file.name,
        rom_bytes=len(pcm), source_text=source,
        dmc_rate=asset.dmc_rate, dmc_length=len(dmc_data),
        dmc_bytes=len(dmc_data), dmc_asm_text=asm_text,
    )
