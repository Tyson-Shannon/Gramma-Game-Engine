"""Runs all converters for one target and writes generated C + a manifest."""

from __future__ import annotations

import json
import re
from dataclasses import replace
from pathlib import Path

from .audio import process_audio
from .grain import transpile as transpile_grain
from .images import emit_image, process_image
from .music import process_music
from .project import load_project
from .targets import PROFILES


def _ident(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def _asm_hex_rows(values: list[int], per_row: int = 16) -> str:
    rows = []
    for start in range(0, len(values), per_row):
        row = ", ".join(f"${value:02X}" for value in values[start:start + per_row])
        rows.append("    .byte " + row)
    return "\n".join(rows)


def _emit_nes_chr(image_results, placements, chr_banks):
    """Build *chr_banks* 8 KB CHR banks for NES.

    Each 8 KB bank holds one 4 KB tile table mirrored into both pattern tables.
    Mirroring keeps PPUCTRL selection irrelevant and preserves the existing
    absolute tile indices. Per-asset `chr_bank` / `chr_tile` settings place
    assets in different banks at the same local tile index, so switching a
    mapper CHR register swaps visible content without changing nametable or OAM
    indices. cc65's crt0 force-imports a 4 KB font; define that symbol
    absolutely so it does not consume CHR space.
    """
    tables = [bytearray(0x1000) for _ in range(chr_banks)]
    used: list[dict[int, str]] = [{} for _ in range(chr_banks)]
    offsets: dict[str, tuple[int, int]] = {}

    def place(name, result, bank, start):
        count = len(result.tiles)
        if bank < 0 or bank >= chr_banks:
            raise ValueError(f"{name}: chr_bank {bank} is out of range")
        if start < 0 or start + count > 256:
            raise ValueError(
                f"{name}: chr_tile {start} with {count} tiles exceeds one "
                "4 KB pattern table")
        for index in range(start, start + count):
            if index in used[bank]:
                raise ValueError(
                    f"{name}: CHR tile {index} in bank {bank} overlaps "
                    f"{used[bank][index]}")
            used[bank][index] = name
        for offset, tile in enumerate(result.tiles):
            tables[bank][(start + offset) * 16:(start + offset + 1) * 16] = tile
        offsets[name] = (bank, start)
        return start + count

    # Explicit tile placements first, then automatic backgrounds from tile 0
    # and automatic sprites from tile 4, preserving the original default layout.
    for name, result in image_results:
        tile = placements[name].chr_tile
        if tile is not None:
            place(name, result, placements[name].chr_bank, tile)
    for bank in range(chr_banks):
        cursor = 0
        for name, result in image_results:
            if (placements[name].chr_bank == bank and
                    placements[name].chr_tile is None and
                    result.kind == "background"):
                cursor = place(name, result, bank, cursor)
        if cursor < 4:
            cursor = 4
        for name, result in image_results:
            if (placements[name].chr_bank == bank and
                    placements[name].chr_tile is None and
                    result.kind != "background"):
                cursor = place(name, result, bank, cursor)

    data = bytes(byte for table in tables for _ in (0, 1) for byte in table)
    # cc65 cannot compile a C array larger than 64 KB, so CHR data is emitted
    # directly into the linker's CHARS segment from assembly. C files still
    # refer to the exported `_nes_chr_data` symbol as before.
    source = "\n".join([
        "; Generated by the Gramma asset pipeline. DO NOT EDIT.",
        f"; {len(data)} bytes in {chr_banks} 8 KB bank(s).",
        ".export _nes_chr_data",
        '.segment "CHARS"',
        "_nes_chr_data:",
        _asm_hex_rows(list(data), 16),
        "",
    ])
    font_source = (
        "; Generated by the Gramma asset pipeline. DO NOT EDIT.\n"
        "; Satisfy cc65's forced NESfont import without reserving 4 KB of\n"
        "; CHR-ROM, so generated background tiles start at PPU $0000.\n"
        ".export NESfont : absolute\n"
        "NESfont = $0000\n"
    )
    return source, font_source, offsets


def generate(root: Path, target: str, project=None,
             mapper_override: dict | None = None) -> dict:
    """Generate assets for *target*; return the manifest dict.

    Callers may pass an already loaded Project and a small mapper override so
    `gr build --mapper ...` can produce layout variants without editing files.
    """
    root = Path(root)
    if project is None:
        project = load_project(root)
    if mapper_override:
        for key, value in mapper_override.items():
            if value is None:
                continue
            if "." in key:
                target_name, field = key.split(".", 1)
                cfg = project.mapper.setdefault(target_name, {})
            else:
                cfg = project.mapper.setdefault("nes", {})
                field = key
            cfg[field] = value
    output = root / "generated" / target
    output.mkdir(parents=True, exist_ok=True)
    chr_banks = int(project.mapper.get("nes", {}).get("chr_banks", 1))

    for pattern in ("*.c", "*.s"):
        for stale in output.glob(pattern):
            stale.unlink()

    manifest = {
        "project": project.name,
        "target": target,
        "declared_sprites": project.max_sprites,
        "assets": [],
        "totals": {"rom_bytes": 0, "unique_tiles": 0},
    }
    if target == "nes":
        manifest["chr_banks"] = chr_banks
    sources: list[str] = []
    overrides = project.targets.get(target, {})
    image_overrides = overrides.get("image", {})
    audio_overrides = overrides.get("audio", {})
    music_overrides = overrides.get("music", {})
    packing = PROFILES.get(target, {}).get("packing", "chunky")
    image_results: list[tuple[str, object]] = []
    placements: dict[str, object] = {}

    for asset in project.images:
        options = image_overrides.get(asset.name)
        if options:
            allowed = {"kind", "bpp", "frame_width", "frame_height",
                       "chr_bank", "chr_tile"}
            asset = replace(asset, **{k: v for k, v in options.items()
                                      if k in allowed})
        placements[asset.name] = asset
        result = process_image(asset, packing)
        image_results.append((asset.name, result))
        entry = {
            "name": asset.name,
            "kind": asset.kind,
            "bpp": result.bpp,
            "packing": result.packing,
            "tile_count": len(result.tile_indices),
            "unique_tiles": result.unique_tiles,
            "palette_colors": len(result.palette),
            "width": result.width,
            "height": result.height,
            "rom_bytes": result.rom_bytes,
            "source": result.source,
        }
        if target == "nes":
            entry["chr_bank"] = asset.chr_bank
            entry["chr_tile"] = asset.chr_tile
        manifest["assets"].append(entry)
        manifest["totals"]["rom_bytes"] += result.rom_bytes
        manifest["totals"]["unique_tiles"] += result.unique_tiles

    tile_exprs: dict[str, str] = {}
    chr_extern = ""
    if target == "nes" and image_results:
        chr_source, font_source, offsets = _emit_nes_chr(
            image_results, placements, chr_banks)
        (output / "nes_font.s").write_text(font_source, encoding="utf-8")
        (output / "chr.s").write_text(chr_source, encoding="utf-8")
        sources += ["nes_font.s", "chr.s"]
        tile_exprs = {
            name: f"nes_chr_data + {(bank * 512 + tile) * 16}"
            for name, (bank, tile) in offsets.items()
        }
        chr_extern = "extern const uint8_t nes_chr_data[];\n\n"
    for name, result in image_results:
        filename = _ident(name) + ".c"
        text = emit_image(result, tile_exprs.get(name))
        if target == "gb":
            # Keep generated art in bank 1 so GBDK's fixed-bank helpers fit
            # below $4000; bank 1 is mapped by default on plain and MBC carts.
            text = "#pragma bank 1\n\n" + text
        if chr_extern:
            text = text.replace("#include <gramma/gramma.h>\n",
                                "#include <gramma/gramma.h>\n\n" + chr_extern,
                                1)
        (output / filename).write_text(text, encoding="utf-8")
        sources.append(filename)

    for asset in project.audio:
        options = audio_overrides.get(asset.name, {})
        if options.get("skip", False):
            continue
        if options.get("sample_rate"):
            asset = replace(asset, sample_rate=int(options["sample_rate"]))
        result = process_audio(asset)
        filename = _ident(asset.name) + ".c"
        text = result.source_text
        if target == "gb":
            text = "#pragma bank 1\n\n" + text
        (output / filename).write_text(text, encoding="utf-8")
        sources.append(filename)
        manifest["assets"].append({
            "name": asset.name,
            "kind": "audio",
            "bpp": 0,
            "tile_count": 0,
            "unique_tiles": 0,
            "palette_colors": 0,
            "rom_bytes": result.rom_bytes,
            "source": result.source,
            "sample_rate": result.sample_rate,
            "duration_ms": result.duration_ms,
        })
        manifest["totals"]["rom_bytes"] += result.rom_bytes

    for asset in project.music:
        options = music_overrides.get(asset.name, {})
        if options.get("skip", False):
            continue
        # Only SMS/Game Gear replay the SN76489 byte stream; all targets still
        # receive the portable gr_note events in the same generated song.
        result = process_music(asset, psg=(target == "sms"))
        filename = _ident(asset.name) + ".c"
        text = result.source_text
        if target == "gb":
            text = "#pragma bank 1\n\n" + text
        (output / filename).write_text(text, encoding="utf-8")
        sources.append(filename)
        manifest["assets"].append({
            "name": asset.name,
            "kind": "music",
            "bpp": 0,
            "tile_count": 0,
            "unique_tiles": 0,
            "palette_colors": 0,
            "rom_bytes": result.rom_bytes,
            "source": result.source,
            "notes": result.note_count,
            "psg_bytes": result.psg_bytes,
            "frames": result.frames,
        })
        manifest["totals"]["rom_bytes"] += result.rom_bytes

    # Grain translation units are emitted into the same generated directory as
    # assets, so every console driver and Meson pick them up automatically.
    for source in project.grain_sources:
        if not source.is_file():
            raise FileNotFoundError(f"Grain source not found: {source}")
        try:
            relative = source.resolve().relative_to(root.resolve())
        except ValueError:
            relative = source
        c_text, checker = transpile_grain(
            source.read_text(encoding="utf-8"), str(relative))
        filename = "grain_" + _ident(source.stem) + ".c"
        (output / filename).write_text(c_text, encoding="utf-8")
        sources.append(filename)
        manifest.setdefault("grain", []).append({
            "source": str(relative),
            "file": filename,
            "entities": [entity.name for entity in checker.program.entities],
            "scenes": [scene.name for scene in checker.program.scenes],
        })

    source_list = ", ".join("'" + name + "'" for name in sources)
    (output / "meson.build").write_text(
        "# Generated by the Gramma asset pipeline. DO NOT EDIT.\n"
        f"generated_sources = files({source_list})\n",
        encoding="utf-8",
    )
    (output / "manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest
